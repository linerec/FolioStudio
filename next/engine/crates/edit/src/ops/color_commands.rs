use super::*;

trait Ts {
    fn ts() -> String;
    fn optional() -> bool { false }
}
impl Ts for String { fn ts() -> String { "string".into() } }
impl Ts for f64 { fn ts() -> String { "number".into() } }
impl Ts for bool { fn ts() -> String { "boolean".into() } }
impl Ts for [f64; 2] { fn ts() -> String { "[number, number]".into() } }
impl<T: Ts> Ts for Vec<T> { fn ts() -> String { format!("({})[]", T::ts()) } }
impl<T: Ts> Ts for Option<T> {
    fn ts() -> String { format!("{} | null", T::ts()) }
    fn optional() -> bool { true }
}
macro_rules! payload {
    ($name:ident { $($field:ident : $ty:ty),* $(,)? }) => {
        #[derive(Clone, Debug, PartialEq, Serialize, Deserialize)]
        pub struct $name { $(pub $field: $ty),* }
        impl Ts for $name {
            fn ts() -> String {
                let fields: Vec<String> = vec![$(format!("{}{}: {}", stringify!($field), if <$ty as Ts>::optional() { "?" } else { "" }, <$ty as Ts>::ts())),*];
                format!("{{ {} }}", fields.join("; "))
            }
        }
    };
}
