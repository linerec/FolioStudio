macro_rules! commands {
    ($($name:ident => $op:literal => $run:path),* $(,)?) => {
        #[derive(Clone, Debug, PartialEq, Serialize, Deserialize)]
        #[serde(tag = "op")]
        pub enum ColorCommand { $(#[serde(rename = $op)] $name($name)),* }
        impl ColorCommand {
            pub(crate) fn run(&self, w: &mut Work<'_>) -> Result<(), EditError> {
                match self { $(Self::$name(p) => $run(w, p)),* }
            }
            pub fn supports(op: &str) -> bool { [$($op),*].contains(&op) }
            pub fn typescript() -> String {
                let variants = vec![$(format!("  | ({{ op: '{}' }} & {})", $op, $name::ts())),*];
                format!("// Generated by folio-edit color_commands.\nexport type ColorCommand =\n{};\n", variants.join("\n"))
            }
        }
    };
}
