#[test]
fn generated_color_types_are_current() {
    let path = std::path::Path::new(env!("CARGO_MANIFEST_DIR")).join("../../../app/renderer/src/features/color/commands.generated.ts");
    let expected = ColorCommand::typescript();
    if std::env::var_os("FOLIO_WRITE_TYPES").is_some() {
        std::fs::create_dir_all(path.parent().unwrap()).unwrap();
        std::fs::write(&path, &expected).unwrap();
    }
    // A Windows checkout may turn the generated file into CRLF; compare line content only.
    assert_eq!(std::fs::read_to_string(path).unwrap().replace("\r\n", "\n"), expected);
}
