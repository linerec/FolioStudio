"""Regenerates src/encodings.rs from pypdf's tables of the Adobe Glyph List and the
Standard / WinAnsi / MacRoman encodings (both BSD-3-Clause).

Usage: python gen_encodings.py ../src/encodings.rs
"""
import sys
import pypdf._codecs as c


def cp(s):
    return ord(s) if isinstance(s, str) and len(s) == 1 else 0


def table(enc):
    v = []
    for i, ch in enumerate(enc):
        u = cp(ch)
        if u == 0xFFFD or i < 32:
            u = 0
        v.append(u)
    return v


std, win, mac = table(c._std_encoding), table(c._win_encoding), table(c._mac_encoding)
for i in (0x81, 0x8D, 0x8F, 0x90, 0x9D):
    win[i] = 0
names = {}
for k, v in c.adobe_glyphs.items():
    if not isinstance(v, str) or len(v) != 1:
        continue
    u = ord(v)
    if u < 0x0500 or 0x2000 <= u <= 0x22FF or 0xFB00 <= u <= 0xFB06 or u == 0x20AC:
        names[k[1:]] = u
items = sorted(names.items())
out = ['//! Simple-font encodings and glyph names for placed PDFs whose fonts are not embedded.', '//!',
       '//! Code → Unicode for StandardEncoding, WinAnsiEncoding and MacRomanEncoding, and Adobe',
       '//! Glyph List names (the Latin, punctuation and symbol subset) → Unicode. Data: the Adobe',
       '//! Glyph List (BSD-3-Clause, Adobe) as tabulated by pypdf (BSD-3-Clause); generated by',
       '//! tools/gen_encodings.py.', '']


def arr(name, v):
    out.append(f'pub static {name}: [u16; 256] = [')
    for i in range(0, 256, 16):
        out.append('    ' + ', '.join(f'0x{x:04X}' for x in v[i:i + 16]) + ',')
    out.append('];')
    out.append('')


arr('STANDARD', std)
arr('WIN_ANSI', win)
arr('MAC_ROMAN', mac)
out.append('/// (glyph name, Unicode), sorted by name.')
out.append(f'pub static GLYPH_NAMES: [(&str, u16); {len(items)}] = [')
for k, u in items:
    out.append(f'    ("{k}", 0x{u:04X}),')
out.append('];')
out.append('''
/// Unicode of a glyph name: the list above, then `uniXXXX` / `uXXXX(XX)`.
pub fn glyph_unicode(name: &str) -> Option<char> {
    if let Ok(i) = GLYPH_NAMES.binary_search_by(|(n, _)| (*n).cmp(name)) {
        return char::from_u32(GLYPH_NAMES[i].1 as u32);
    }
    let base = name.split('.').next().unwrap_or(name);
    if base != name {
        return glyph_unicode(base);
    }
    let hex = name.strip_prefix("uni").filter(|h| h.len() == 4).or_else(|| name.strip_prefix('u').filter(|h| (4..=6).contains(&h.len())))?;
    char::from_u32(u32::from_str_radix(hex, 16).ok()?)
}''')
open(sys.argv[1], 'w', encoding='utf-8').write('\n'.join(out) + '\n')
print(len(items), 'names')
