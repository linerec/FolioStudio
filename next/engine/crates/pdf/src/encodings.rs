/// Unicode of a glyph name: the list above, then `uniXXXX` / `uXXXX(XX)`.
pub fn glyph_unicode(name: &str) -> Option<char> {
    if let Ok(i) = GLYPH_NAMES.binary_search_by(|(n, _)| (*n).cmp(name)) {
        return char::from_u32(GLYPH_NAMES[i].1 as u32);
    }
    let base = name.split('.').next().unwrap_or(name);
    if base != name {
        return glyph_unicode(base);
    }
    let hex = name.strip_prefix("uni").filter(|h| h.len() == 4).or_else(|| name.strip_prefix('u').filter(|h| (4..=6).contains(&h.len())))?;
    char::from_u32(u32::from_str_radix(hex, 16).ok()?)
}
