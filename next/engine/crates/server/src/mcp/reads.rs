pub fn get(name: &str) -> Option<&'static Read> {
    READS.iter().find(|read| read.name == name)
}

pub struct InputFile {
    pub field: &'static str,
    pub native: bool,
    pub extensions: &'static [&'static str],
}

pub fn input_file(name: &str) -> Option<InputFile> {
    let (field, native, extensions): (_, _, &[&str]) = match name {
        "conditionsFile" => ("path", false, &["folio", "idml"]),
        "pdfComments" => ("path", false, &["pdf"]),
        "placeInfo" | "fileMetadata" => ("file", true, &[]),
        "preflightProfileFile" => ("path", false, &["json"]),
        "strokeStylesFile" => ("path", false, &["idml"]),
        "textImportInfo" => ("file", true, &["txt", "rtf", "docx"]),
        "tocImportStyles" => ("path", true, &["idml", "folio"]),
        "trapPresetsFile" => ("path", false, &["folio", "idml"]),
        _ => return None,
    };
    Some(InputFile { field, native, extensions })
}
