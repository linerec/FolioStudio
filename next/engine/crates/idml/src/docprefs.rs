//! Document preference attributes, defaults and accepted values.
use crate::xml;
use serde_json::{Value, json};
use std::collections::BTreeMap;

pub const PART: &str = "Resources/Preferences.xml";
pub enum Kind { Switch, Number(f64, f64), Choice(&'static [&'static str]) }
pub struct Field {
    pub element: &'static str, pub attr: &'static str, pub initial: &'static str,
    pub kind: Kind, pub recompose: bool,
}
macro_rules! fields {
    ($( $element:literal { $( $attr:literal, $initial:literal, $kind:expr, $recompose:literal; )* } )*) => {
        pub static FIELDS: &[Field] = &[$($(Field { element: $element, attr: $attr, initial: $initial, kind: $kind, recompose: $recompose },)*)*];
    }
}
