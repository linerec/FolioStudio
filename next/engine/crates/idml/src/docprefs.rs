impl Field {
    pub fn key(&self) -> String { format!("{}.{}", self.element, self.attr) }
    pub fn value(&self, value: &Value) -> Result<String, String> {
        let valid = match self.kind {
            Switch => value.is_boolean(),
            Number(lo, hi) => value.as_f64().is_some_and(|v| v.is_finite() && v >= lo && v <= hi),
            Choice(names) => value.as_str().is_some_and(|v| names.contains(&v)),
        };
        if !valid { return Err(format!("invalid {}: {}", self.key(), value)); }
        Ok(value.as_str().map(str::to_owned).unwrap_or_else(|| value.to_string()))
    }
    fn typed(&self, text: &str) -> Value {
        match self.kind { Choice(_) => json!(text), _ => serde_json::from_str(text).unwrap_or(Value::Null) }
    }
}

pub fn field(key: &str) -> Result<&'static Field, String> {
    FIELDS.iter().find(|f| f.key() == key).ok_or_else(|| format!("unknown document preference: {key}"))
}

pub fn settings(source: &str) -> Result<BTreeMap<String, Value>, String> {
    let root = xml::parse(source).map_err(|e| e.0)?;
    Ok(FIELDS.iter().map(|f| {
        let value = root.child(f.element).and_then(|e| e.attr(f.attr)).unwrap_or(f.initial);
        (f.key(), f.typed(value))
    }).collect())
}

pub fn typescript() -> String {
    let schema: BTreeMap<_, _> = FIELDS.iter().map(|f| {
        let mut v = json!({"initial": f.typed(f.initial)});
        match f.kind { Number(lo, hi) => { v["min"] = json!(lo); v["max"] = json!(hi); }, Choice(names) => v["choices"] = json!(names), Switch => {} }
        (f.key(), v)
    }).collect();
    format!("// Generated by folio-idml; do not edit.\nexport const documentPreferenceSchema = {} as const;\n", serde_json::to_string_pretty(&schema).expect("schema contains only JSON values with string keys"))
}

#[cfg(test)]
mod tests {
    use super::*;
    #[test]
    fn measured_ranges_and_types() {
        for name in ["SuperscriptSize", "SubscriptSize", "SmallCap"] {
            let f = field(&format!("TextPreference.{name}")).unwrap();
            for v in [1.0, 58.3, 200.0] { assert!(f.value(&json!(v)).is_ok()); }
            for v in [0.0, 200.01, 501.0] { assert!(f.value(&json!(v)).is_err()); }
            assert!(f.value(&json!("70")).is_err());
        }
        let f = field("TextPreference.SuperscriptPosition").unwrap();
        for v in [-500.0, 0.0, 500.0] { assert!(f.value(&json!(v)).is_ok()); }
        assert!(f.value(&json!(-500.01)).is_err());
        assert!(field("TextPreference.TypographersQuotes").unwrap().value(&json!(1)).is_err());
        assert!(field("unknown").is_err());
    }
}
