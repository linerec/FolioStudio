// Writes next/shared/tool-help.json: the tool help of the screen (renderer/src/ui/toolhelp.ts, uix-e1) in every language the app has, for
// whatever reads it without the screen (the MCP tool descriptions, docs). One owner: the words are toolhelp.ts (Korean source in tr(),
// English in i18n/messages.en.ts); a tool's name and key are ui/tools.tsx's. The screen does not read this file.
// Run: node next/app/scripts/gen-tool-help.cjs        (--check: fail when the file is not what this writes)
const fs = require('node:fs'), path = require('node:path');
const { root, runtime } = require('./i18n-source.cjs');
const OUT = path.resolve(root, '../../../shared/tool-help.json');

function tools() {
  // the tool rows of ui/tools.tsx: { id: 'selection', get label() { return tr("선택 도구"); }, key: 'V', icon: … }
  const text = fs.readFileSync(path.join(root, 'ui/tools.tsx'), 'utf8');
  const rows = new Map();
  for (const m of text.matchAll(/\{ id: '(\w+)', get label\(\) \{ return tr\("([^"]+)"\); \}, (?:key: '((?:[^'\\]|\\.)*)', )?icon: /g)) {
    rows.set(m[1], { label: m[2], key: m[3] === undefined ? null : m[3].replace(/\\(.)/g, '$1') });
  }
  return rows;
}

function build() {
  const rows = tools(), languages = ['ko', 'en'];
  const loaded = Object.fromEntries(languages.map((lang) => {
    const { load } = runtime(lang === 'ko' ? 'ko-KR' : 'en-US');
    return [lang, { help: load(path.join(root, 'ui/toolhelp')), tr: load(path.join(root, 'i18n')).tr }];
  }));
  const items = loaded.ko.help.HELP_IDS.map((id) => {
    const tool = loaded.ko.help.isToolHelp(id) ? rows.get(id) : null;
    if (loaded.ko.help.isToolHelp(id) && !tool) throw new Error(`tool ${id} is not in ui/tools.tsx`);
    const entry = (lang) => {
      const { help, tr } = loaded[lang], e = help.helpEntry(id);
      return { name: tool ? tr(tool.label) : e.name(), summary: e.summary(), detail: e.detail() };
    };
    const e = loaded.ko.help.helpEntry(id);
    return {
      id, kind: tool ? 'tool' : 'control',
      // the default keys (a person may change a command's keys in Edit ▸ Keyboard Shortcuts; the screen shows the keymap's)
      keys: tool ? (tool.key ? [tool.key] : []) : e.keys ?? [],
      commands: e.command ?? [],
      ...Object.fromEntries(languages.map((lang) => [lang, entry(lang)])),
    };
  });
  return JSON.stringify({
    note: 'Generated by next/app/scripts/gen-tool-help.cjs from next/app/renderer/src/ui/toolhelp.ts and ui/tools.tsx. Do not edit.',
    languages, items,
  }, null, 1) + '\n';
}

const text = build();
if (process.argv.includes('--check')) {
  const now = fs.existsSync(OUT) ? fs.readFileSync(OUT, 'utf8').replace(/\r\n/g, '\n') : '';
  if (now !== text) { console.error(`${path.relative(process.cwd(), OUT)} is not what gen-tool-help.cjs writes (run it)`); process.exit(1); }
  console.log('tool-help.json is current');
} else {
  fs.writeFileSync(OUT, text);
  console.log(`wrote ${path.relative(process.cwd(), OUT)} (${JSON.parse(text).items.length} items)`);
}
