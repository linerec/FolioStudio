"""Generate the object-style command union from the Rust definition registry."""
import re
from pathlib import Path
root=Path(__file__).resolve().parents[3]
source=(root/'next/engine/crates/edit/src/ops/objectstyledefs.rs').read_text(encoding='utf-8')
registry=source.split('definitions! {',1)[1].split('\n}',1)[0]
types={'String':'string','Vec<String>':'string[]','Map<String, Value>':'Record<string, unknown>'}
rows=[]
for name,fields in re.findall(r'(\w+)\s*\{([^}]+)\}\s*=>',registry):
    parts=[f"op: '{name[0].lower()+name[1:]}'"]
    for key,ty in re.findall(r'(\w+):\s*(Map<String, Value>|Vec<String>|Option<String>|String)',fields):
        optional=ty.startswith('Option<')
        key=re.sub(r'_([a-z])',lambda m:m[1].upper(),key)
        parts.append(f'{key}{"?" if optional else ""}: {"string" if optional else types[ty]}')
    rows.append('  | { '+'; '.join(parts)+' }')
out=root/'next/app/renderer/src/objectstyles.generated.ts'
out.write_text('// Generated by scripts/gen-objectstyle-types.py from the Rust command registry.\nexport type ObjectStyleCommand =\n'+'\n'.join(rows)+';\n',encoding='utf-8')
