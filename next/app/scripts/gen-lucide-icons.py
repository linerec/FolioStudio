"""Make renderer/src/ui/icons.lucide.ts from Lucide's SVG files (uix-b1, 2026-11-20).

Lucide (https://lucide.dev, ISC licence, notice in THIRD_PARTY_NOTICES.txt) draws on a 24-unit grid with a 2-unit
round stroke. Folio's own icons (ui/icons.tsx) draw on a 20-unit grid with a 1.5-unit round stroke; icons.tsx scales
these shapes by 20/24 with a 1.8 stroke, so both kinds come out the same weight.

usage: python -I -B next/app/scripts/gen-lucide-icons.py <folder with lucide-static/icons/*.svg> [version]
  (the files come from https://cdn.jsdelivr.net/npm/lucide-static@<version>/icons/<name>.svg)
Only the names in NAMES are taken: the Folio name on the left, the Lucide name on the right.
"""
import json
import sys
import xml.etree.ElementTree as ET
from pathlib import Path

sys.dont_write_bytecode = True
OUT = Path(__file__).resolve().parent.parent / 'renderer/src/ui/icons.lucide.ts'
NAMES = {
    'chevronLeft': 'chevron-left', 'chevronRight': 'chevron-right', 'doubleLeft': 'chevrons-left', 'doubleRight': 'chevrons-right',
    'first': 'chevron-first', 'last': 'chevron-last', 'menu': 'menu', 'close': 'x', 'eye': 'eye', 'lock': 'lock', 'pen2': 'pencil',
    'newPage': 'file-plus', 'trash': 'trash-2', 'links': 'link', 'relink': 'link', 'goTo': 'arrow-right', 'refresh': 'refresh-cw',
    'plus': 'plus', 'folder': 'folder', 'project': 'folder', 'document': 'file-text', 'file': 'file', 'pages': 'file',
    'rotateCw': 'rotate-cw', 'rotateCcw': 'rotate-ccw', 'flipH': 'flip-horizontal-2', 'flipV': 'flip-vertical-2',
    'selContainer': 'arrow-up', 'selContent': 'arrow-down', 'selPrev': 'arrow-left', 'selNext': 'arrow-right',
    'warning': 'triangle-alert', 'search': 'search', 'zoom': 'search', 'workspace': 'panels-top-left', 'info': 'info',
    'history': 'history', 'preflight': 'circle-check', 'layers': 'layers', 'swatches': 'layout-grid', 'separations': 'blend',
    'hand': 'hand', 'eyedropper': 'pipette', 'pencil': 'pencil', 'pen': 'pen-tool', 'scissors': 'scissors', 'measure': 'ruler',
    'note': 'sticky-note', 'screenPresentation': 'monitor', 'type': 'type', 'paragraph': 'pilcrow',
    'alignLeft': 'align-start-vertical', 'alignHCenter': 'align-center-vertical', 'alignRight': 'align-end-vertical',
    'alignTop': 'align-start-horizontal', 'alignVCenter': 'align-center-horizontal', 'alignBottom': 'align-end-horizontal',
    'textAlignLeft': 'align-left', 'textAlignCenter': 'align-center', 'textAlignRight': 'align-right', 'textJustifyAll': 'align-justify',
    'more': 'ellipsis',
    # the project explorer (uix-c1): file kinds, its header buttons and context menu
    'book': 'book', 'library': 'library-big', 'image': 'image', 'fontFile': 'file-type', 'dataFile': 'file-spreadsheet',
    'indesignFile': 'file-input', 'folderOpen': 'folder-open', 'folderPlus': 'folder-plus', 'bookPlus': 'book-plus',
    'libraryPlus': 'square-library', 'collapseAll': 'chevrons-down-up', 'copy': 'copy', 'external': 'external-link',
    'filter': 'list-filter', 'sidebar': 'panel-left',
}
CAMEL = {'stroke-width': 'strokeWidth', 'fill-rule': 'fillRule', 'clip-rule': 'clipRule'}


def shapes(svg: Path):
    root = ET.fromstring(svg.read_text(encoding='utf-8'))
    out = []
    for el in root:
        tag = el.tag.split('}')[-1]
        if tag not in ('path', 'circle', 'rect', 'line', 'polyline', 'polygon', 'ellipse'):
            raise SystemExit(f'{svg.name}: unexpected <{tag}>')
        out.append([tag, {CAMEL.get(k, k): v for k, v in el.attrib.items()}])
    return out


def main():
    src = Path(sys.argv[1])
    version = sys.argv[2] if len(sys.argv) > 2 else '0.460.0'
    data = {name: shapes(src / f'{lucide}.svg') for name, lucide in NAMES.items()}
    lines = [
        f'// Generated by next/app/scripts/gen-lucide-icons.py from lucide-static {version} (ISC licence, THIRD_PARTY_NOTICES.txt).',
        '// Do not edit by hand: Folio name -> the shapes of the Lucide icon on its 24-unit grid (ui/icons.tsx scales them to 20).',
        'export const LUCIDE: Record<string, [string, Record<string, string>][]> = {',
    ]
    for name, els in data.items():
        lines.append(f'  {name}: {json.dumps(els, ensure_ascii=False)},')
    lines.append('};')
    OUT.write_text('\n'.join(lines) + '\n', encoding='utf-8', newline='\n')
    print(f'{len(data)} icons -> {OUT}')


if __name__ == '__main__':
    main()
