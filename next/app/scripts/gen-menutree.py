"""Build both Folio menu language tables. The menu structure lives in ui/menutree.ts."""
import argparse
import json
import re
from pathlib import Path

APP = Path(__file__).resolve().parents[1]


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    labels = json.loads((APP / "scripts/menu-labels.json").read_text(encoding="utf8"))
    tree = (APP / "renderer/src/ui/menutree.ts").read_text(encoding="utf8")
    used = set(re.findall(r"'((?:menu|command)\.[^']+)'", tree))
    missing = sorted(used - labels.keys())
    if missing:
        raise SystemExit("Missing menu labels: " + ", ".join(missing))
    if any(not isinstance(pair, list) or len(pair) != 2 or
           not all(isinstance(item, str) and item for item in pair) for pair in labels.values()):
        raise SystemExit("Each menu label needs Korean and English text")
    for index, locale in enumerate(("ko", "en")):
        table = {key: pair[index] for key, pair in labels.items()}
        output = ("// Generated by scripts/gen-menutree.py from scripts/menu-labels.json.\n"
                  + "export default " + json.dumps(table, ensure_ascii=False, indent=2) + " as const;\n")
        path = APP / f"renderer/src/i18n/menus.{locale}.ts"
        if args.check:
            if path.read_text(encoding="utf8") != output:
                raise SystemExit(f"Run gen-menutree.py to update {path.name}")
        else:
            path.write_text(output, encoding="utf8", newline="\n")


if __name__ == "__main__":
    main()
