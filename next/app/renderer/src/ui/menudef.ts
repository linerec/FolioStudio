/** Every command's label and keys: Folio's own first, then the InDesign items (greyed out). */
export const SPECS: Record<string, Spec> = {};
for (const [id, spec] of Object.entries(FOLIO_SPECS)) {
  SPECS[id] = { get label() { return t(`command.${id}`); }, keys: spec.keys };
}
for (const [id, spec] of Object.entries(MENU_SPECS)) if (!(id in SPECS)) SPECS[id] = spec;

export type MenuEntry = { cmd: string } | { sep: true } | { label: string; sub: MenuEntry[] };
export type MenuDef = { label: string; mnemonic: string; items: MenuEntry[] };

export { CONTEXT_MENUS, PANEL_MENUS };

/** The menu bar (InDesign's, see menutree.ts) with File ▸ Open Recent filled in. */
export function buildMenus(recent: MenuEntry[], presets: MenuEntry[] = [], workspaces: MenuEntry[] = []): MenuDef[] {
  const items = recent.length ? recent : [{ cmd: 'recent.none' }];
  return MAIN_MENUS.map((m) => ({
    ...m,
    items: m.items.map((it) => ('sub' in it && it.label === t(RECENT_SUBMENU) ? { label: it.label, sub: items }
      // Window ▸ Workspace: the saved workspaces follow the built-in one
      : 'sub' in it && it.sub.some((x) => 'cmd' in x && x.cmd === 'window.workspaceClassic') ? { label: it.label, sub: it.sub.flatMap((x) => ('cmd' in x && x.cmd === 'window.workspaceClassic' ? [x, ...workspaces] : [x])) }
      // File ▸ Document Presets: Define…, then [Default] and the user's presets
      : 'sub' in it && it.sub.some((x) => 'cmd' in x && x.cmd === 'id.file.documentPresets.default') ? { label: it.label, sub: [...it.sub, ...presets] } : it)),
  }));
}
